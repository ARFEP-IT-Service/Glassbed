"""Android launcher icons for mobile/ from shared/icon/glassbed.svg (design F).

    mipmap-anydpi-v26/ic_launcher.xml   adaptive icon: ink background, vector foreground,
                                        monochrome layer for themed icons (Android 13+)
    drawable/ic_launcher_foreground.xml the sheet, its folded corner and the blue band as vectors
    mipmap-*/ic_launcher.png            full icon as PNG (fallback, rendered with Qt's SVG renderer)
    assets/icon/glassbed.png            the icon for the About screen

Run with the build venv (needs PySide6):  .venv-build\\Scripts\\python tools/make_android_icons.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

from PySide6.QtCore import QRectF, Qt
from PySide6.QtGui import QGuiApplication, QImage, QPainter
from PySide6.QtSvg import QSvgRenderer

ROOT = Path(__file__).resolve().parent.parent
SVG = ROOT / "shared" / "icon" / "glassbed.svg"
RES = ROOT / "mobile" / "android" / "app" / "src" / "main" / "res"
DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
BACKGROUND = "#212830"


def shapes() -> list[tuple[str, str]]:
    """(path data, fill) of the drawing on top of the rounded background square."""
    svg = SVG.read_text(encoding="utf-8")
    return re.findall(r'<path d="([^"]+)" fill="([^"]+)"', svg)


def foreground(monochrome: bool) -> str:
    # 108 dp canvas, everything inside the 66 dp safe zone: the art (x 72–190, y 44–212 in the
    # 256 viewBox) is scaled to 58 dp high and centred
    paths = shapes()
    s = 58 / 168
    tx, ty = 54 - 131 * s, 54 - 128 * s
    body = "\n".join(
        f'        <path android:pathData="{d}" android:fillColor="{"#FFFFFFFF" if monochrome else fill.upper()}"/>'
        for d, fill in paths)
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- generated by tools/make_android_icons.py from shared/icon/glassbed.svg -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="108dp" android:height="108dp"\n'
            f'    android:viewportWidth="108" android:viewportHeight="108">\n'
            f'    <group android:scaleX="{s:.5f}" android:scaleY="{s:.5f}"\n'
            f'        android:translateX="{tx:.4f}" android:translateY="{ty:.4f}">\n'
            f'{body}\n    </group>\n</vector>\n')


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- generated by tools/make_android_icons.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
"""

COLORS = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- generated by tools/make_android_icons.py -->
<resources>
    <color name="ic_launcher_background">{BACKGROUND}</color>
</resources>
"""


def render(size: int) -> QImage:
    img = QImage(size, size, QImage.Format.Format_ARGB32)
    img.fill(Qt.GlobalColor.transparent)
    p = QPainter(img)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    QSvgRenderer(str(SVG)).render(p, QRectF(0, 0, size, size))
    p.end()
    return img


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def main() -> None:
    QGuiApplication(sys.argv[:1] + ["-platform", "offscreen"])
    write(RES / "drawable" / "ic_launcher_foreground.xml", foreground(False))
    write(RES / "drawable" / "ic_launcher_monochrome.xml", foreground(True))
    write(RES / "mipmap-anydpi-v26" / "ic_launcher.xml", ADAPTIVE)
    write(RES / "values" / "ic_launcher_colors.xml", COLORS)
    for density, size in DENSITIES.items():
        out = RES / f"mipmap-{density}" / "ic_launcher.png"
        out.parent.mkdir(parents=True, exist_ok=True)
        render(size).save(str(out))
    about = ROOT / "mobile" / "assets" / "icon" / "glassbed.png"
    about.parent.mkdir(parents=True, exist_ok=True)
    render(256).save(str(about))
    print(f"wrote adaptive icon, {len(DENSITIES)} PNG sizes and {about.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
