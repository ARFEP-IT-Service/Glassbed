def _translations() -> dict[str, dict[str, str]]:
    """TRANSLATIONS from glassbed/i18n.py (standard library only, no Qt needed)."""
    sys.path.insert(0, str(ROOT))
    from glassbed.i18n import TRANSLATIONS
    return TRANSLATIONS


def build() -> dict[str, bytes]:
    tr = _translations()
    missing = [(lang, k) for k in SHARED_KEYS for lang in ("de", "tr") if k not in tr[lang]]
    if missing:
        sys.exit("ERROR: no translation in glassbed/i18n.py for: " + ", ".join(f"{l}:{k!r}" for l, k in missing))
    data = {
        "_comment": "Generated by tools/export_shared.py from glassbed/i18n.py – do not edit by hand.",
        "languages": {"de": "Deutsch", "en": "English", "tr": "Türkçe"},
        "texts": {k: {"en": k, "de": tr["de"][k], "tr": tr["tr"][k]} for k in SHARED_KEYS},
    }
    text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    i18n, icon = text.encode("utf-8"), ICON_SRC.read_bytes()
    return {"shared/i18n.json": i18n, "shared/icon/glassbed.svg": icon,
            "mobile/assets/i18n/shared.json": i18n, "mobile/assets/icon/glassbed.svg": icon}


def main() -> None:
    files = build()
    if "--check" in sys.argv:
        stale = [name for name, data in files.items()
                 if not (ROOT / name).is_file() or (ROOT / name).read_bytes() != data]
        if stale:
            sys.exit("ERROR: shared/ is out of date (run python tools/export_shared.py): " + ", ".join(stale))
        print("shared/ is up to date")
        return
    for name, data in files.items():
        target = ROOT / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    print(f"wrote {len(files)} files (shared/ and mobile/assets/) ({len(SHARED_KEYS)} texts)")


if __name__ == "__main__":
    main()
