def _check_texts(texts: dict) -> list[str]:
    problems = []
    for key, entry in texts.items():
        for lang in ("en", "de", "tr"):
            if not str(entry.get(lang, "")).strip():
                problems.append(f"{lang} missing: {key!r}")
        holes = {lang: sorted(re.findall(r"\{(\w+)\}", str(entry.get(lang, "")))) for lang in ("en", "de", "tr")}
        if len({tuple(v) for v in holes.values()}) > 1:
            problems.append(f"placeholders differ: {key!r} {holes}")
    return problems


def build() -> dict[str, bytes]:
    master = MASTER.read_bytes()
    data = json.loads(master.decode("utf-8"))
    texts = data["texts"]
    problems = _check_texts(texts) + [f"Android text missing in shared/i18n.json: {k!r}"
                                      for k in ANDROID_KEYS if k not in texts]
    if problems:
        sys.exit("ERROR: shared/i18n.json\n  " + "\n  ".join(problems))
    android = {"_comment": ANDROID_COMMENT, "languages": data["languages"],
               "texts": {k: {lang: texts[k][lang] for lang in ("en", "de", "tr")} for k in ANDROID_KEYS}}
    icon = ICON_SRC.read_bytes()
    return {"glassbed/assets/i18n.json": master,
            "mobile/assets/i18n/shared.json": (json.dumps(android, ensure_ascii=False, indent=2) + "\n").encode("utf-8"),
            "shared/icon/glassbed.svg": icon, "mobile/assets/icon/glassbed.svg": icon}


def main() -> None:
    files = build()
    if "--check" in sys.argv:
        stale = [name for name, data in files.items()
                 if not (ROOT / name).is_file() or (ROOT / name).read_bytes() != data]
        if stale:
            sys.exit("ERROR: shared/ is out of date (run python tools/export_shared.py): " + ", ".join(stale))
        print("shared/ and its copies are up to date")
        return
    for name, data in files.items():
        target = ROOT / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    print(f"wrote {len(files)} files ({len(json.loads(MASTER.read_text(encoding='utf-8'))['texts'])} texts, {len(ANDROID_KEYS)} for Android)")


if __name__ == "__main__":
    main()
